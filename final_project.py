class TDManagement:
    def __init__(self):
        self.vehicles = []

    def insert_vehicle(self, v_id, v_type, speed):
        vehicle = {"id": v_id, "type": v_type, "speed": speed}
        self.vehicles.append(vehicle)

    def analyze_traffic(self):
        C = 0
        T = 0
        MC = 0

        for v in self.vehicles:
            if v["type"] == "Car":
                C += 1
            elif v["type"] == "Truck":
                T += 1
            elif v["type"] == "Motorcycle":
                MC += 1

        total = len(self.vehicles)
        print(f"Total: {total}")

        if total > 0:
            print(f"Car: {C} = {round(C / total * 100, 1)}%")
            print(f"Truck: {T} = {round(T / total * 100, 1)}%")
            print(f"Motorcycle: {MC} = {round(MC / total * 100, 1)}%")
        print("-----------")

    def delete_vehicle(self, v_id):
        for i in range(len(self.vehicles)):
            if self.vehicles[i]["id"] == v_id:
                self.vehicles.pop(i)
                break

